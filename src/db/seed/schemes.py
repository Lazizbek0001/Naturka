def drawing_data(key: str) -> dict:
    return json.loads((DRAWINGS / PRESETS[key]["drawing"]).read_text(encoding="utf-8"))


def match(station) -> str | None:
    """Заготовка для станции: по коду или по названию."""
    code, name = (station.code or "").upper(), (station.name or "").lower()
    for key, p in PRESETS.items():
        if code == p["code"] or code in p["aliases"] or p["name"].lower() in name:
            return key
    return None


def plan(config: dict) -> list[dict]:
    """Ведомость путей заготовки: [{code, type, length}]."""
    out = []
    for park in config.get("parks", []):
        for t in park["tracks"]:
            out.append({"code": t[0], "length": t[1], "type": t[2] if len(t) > 2 else park["type"]})
    for s in config.get("singles", []):
        out.append({"code": s["code"], "length": s.get("length"), "type": s["type"]})
    return out
